#include<stdio.h>

int main(){
  printf("\n");

  // == igualdade
  // != diferença
  // < menor
  // > maior
  // <= menor ou igual
  // >= maior igual

  printf("Case 1 == true, 0 == false\n");

  printf("(2 == 5) ? %i\n", 2 == 5);
  printf("(2 != 5) ? %i\n", 2 != 5);
  printf("(2 < 5) ? %i\n", 2 < 5);
  printf("(2 > 5) ? %i\n", 2 > 5);
  printf("(2 <= 5) ? %i\n", 2 <= 5);
  printf("(2 >= 5) ? %i\n", 2 >= 5);

  printf("\n");
  return 0;
}
